public class charr {
    public static void main(String[] args) {
        System.out.println("@"); // @
        System.out.println((int) '@'); // 64
        System.out.println('@' + 0); // 64
        System.out.println((char) 125); // }
        System.out.println('@' + 10); // 74
        System.out.println("@" + 10); // @10
        System.out.println('A' + 'a'); // 162
        System.out.println('t' + 'T'); // 200
        System.out.println('2' + 2); // 52
        System.out.println("2" + 2); // 22
        System.out.println('2' + '2'); // 100
        System.out.println('a' > 100); // false
        System.out.println('A' > 50); // true
        System.out.println('d' + 20 - '2'); // 70
        System.out.println('A' - 'a'); // -32
        System.out.println('t' - 'T'); // 32
    }
}
